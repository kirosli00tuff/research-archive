#!/usr/bin/env python3
"""Build findings/<agentdir>/INDEX.md from the per-repository JSON files written by an agent.

Usage: tools/build_index.py findings/agentA [--title "Agent A"]
Deterministic: no LLM. Reads every *.json directly under the directory (not seeded/, not
_drafts/), validates required keys, and writes INDEX.md with a severity-ranked register and
count tables. Exits non-zero on malformed JSON so problems are visible, never silently skipped.
"""
import json, sys, os, glob, collections

REQ = ["id","repo","sha","agent","direction","hypothesis_or_artifact","class","severity","label",
       "claim_quote","claim_file","claim_line","evidence_summary","evidence_refs","would_resolve",
       "confidence","invalidated_by_later_commits","disclosed_by_authors"]
SEV_ORDER = {"S1":0,"S2":1,"S3":2,"S4":3}

def main():
    d = sys.argv[1].rstrip("/")
    title = sys.argv[sys.argv.index("--title")+1] if "--title" in sys.argv else os.path.basename(d)
    rows, problems = [], []
    for f in sorted(glob.glob(os.path.join(d, "*.json"))):
        try:
            data = json.load(open(f))
        except Exception as e:
            problems.append(f"{f}: JSON parse error: {e}"); continue
        if isinstance(data, dict) and "findings" in data: data = data["findings"]
        if not isinstance(data, list):
            problems.append(f"{f}: top level is not a list"); continue
        for i, r in enumerate(data):
            missing = [k for k in REQ if k not in r]
            if missing: problems.append(f"{f}[{i}] {r.get('id','?')}: missing {missing}")
            r["_src"] = os.path.basename(f)
            rows.append(r)
    ids = collections.Counter(r.get("id") for r in rows)
    for k, v in ids.items():
        if v > 1: problems.append(f"duplicate id {k} x{v}")
    rows.sort(key=lambda r: (SEV_ORDER.get(r.get("severity"), 9), r.get("repo",""), r.get("id","")))
    by = lambda key: collections.Counter(r.get(key) for r in rows)
    out = [f"# {title} — findings index", "",
           f"Generated by tools/build_index.py from {len(rows)} findings in {d}/*.json. Deterministic; no model involved.", ""]
    if problems:
        out += ["## Validation problems", ""] + [f"- {p}" for p in problems] + [""]
    out += ["## Counts", ""]
    for key, name in [("severity","Severity"),("class","Class"),("label","Label"),("direction","Direction"),("repo","Repository"),("confidence","Confidence")]:
        c = by(key)
        out.append(f"**{name}:** " + ", ".join(f"{k}: {v}" for k, v in sorted(c.items(), key=lambda kv: (SEV_ORDER.get(kv[0],9), str(kv[0])))))
        out.append("")
    disc = sum(1 for r in rows if r.get("disclosed_by_authors"))
    inval = sum(1 for r in rows if r.get("invalidated_by_later_commits"))
    out += [f"**Disclosed by authors:** {disc} of {len(rows)}   **Could be invalidated by later commits:** {inval} of {len(rows)}", ""]
    out += ["## Register (severity-ranked)", "", "| ID | Repo | Sev | Class | Label | Conf | Hypothesis / artifact | Claim (file:line) | Source file |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        claim = f"{r.get('claim_file','?')}:{r.get('claim_line','?')}"
        hyp = str(r.get("hypothesis_or_artifact",""))[:70].replace("|","/")
        out.append(f"| {r.get('id')} | {r.get('repo')} | {r.get('severity')} | {r.get('class')} | {r.get('label')} | {r.get('confidence')} | {hyp} | {claim} | {r['_src']} |")
    out.append("")
    open(os.path.join(d, "INDEX.md"), "w").write("\n".join(out))
    print(f"wrote {d}/INDEX.md: {len(rows)} findings, {len(problems)} problems")
    for p in problems: print("PROBLEM:", p)
    return 1 if problems else 0

if __name__ == "__main__":
    sys.exit(main())
